from __future__ import annotations

from pathlib import Path
from typing import Protocol, runtime_checkable

from qeval.adapters.common import Outcome
from qeval.sandbox import Sandbox


@runtime_checkable
class Adapter(Protocol):
    NAME: str
    FINISHED: set[str]
    FINISH_WAITS_FOR_REVIEW: bool
    MERGED: str | None

    def binaries(self, quadratic: Path) -> dict[str, Path]: ...
    def setup(self, sb: Sandbox, repo: Path) -> None: ...
    def seed(self, sb: Sandbox, repo: Path) -> dict[str, str]: ...
    def agent_env(self, sb: Sandbox, repo: Path, agent: str, distinct: bool) -> dict: ...
    def new_issue(self, sb: Sandbox, repo: Path, title: str, description: str = "base") -> str: ...
    def claim(self, sb: Sandbox, cwd: Path, issue: str, env: dict) -> Outcome: ...
    def holder(self, sb: Sandbox, repo: Path, issue: str) -> str: ...
    def append(self, sb: Sandbox, cwd: Path, issue: str, env: dict, text: str) -> Outcome: ...
    def appended(self, sb: Sandbox, repo: Path, issue: str) -> str: ...
    def rewrite(self, sb: Sandbox, cwd: Path, issue: str, env: dict, line: str) -> Outcome: ...
    def rewritten(self, sb: Sandbox, repo: Path, issue: str) -> str: ...
    def release(self, sb: Sandbox, cwd: Path, issue: str, env: dict) -> object: ...
    def set_priority(self, sb: Sandbox, repo: Path, issue: str, priority: int) -> object: ...
    def finish(self, sb: Sandbox, cwd: Path, issue: str, env: dict) -> object: ...
    def history_answers(self, sb: Sandbox, repo: Path, x: str, marks: dict) -> dict: ...
    def human_view(self, sb: Sandbox, repo: Path) -> tuple[int, list[dict]]: ...
    def instructions(self, sb: Sandbox, repo: Path) -> dict[str, str]: ...
    def mcp_command(self, sb: Sandbox, repo: Path) -> tuple[list[str], dict]: ...
    def finished(self, sb: Sandbox, repo: Path, issue: str) -> bool: ...
    def board(self, sb: Sandbox, repo: Path) -> list[dict]: ...
    def take_record(self, sb: Sandbox, repo: Path, issues: list[str]) -> list[dict]: ...
    def status(self, sb: Sandbox, repo: Path, issue: str) -> str: ...
    def after_deploy(self, sb: Sandbox, repo: Path, issue: str) -> dict: ...
    def import_findings(self, sb: Sandbox, repo: Path, path: Path) -> dict: ...
    def finding_states(self, sb: Sandbox, repo: Path) -> dict[str, bool]: ...
    def stop(self, sb: Sandbox, repo: Path) -> None: ...
    def dump(self, sb: Sandbox, repo: Path, issue: str) -> list[str]: ...
